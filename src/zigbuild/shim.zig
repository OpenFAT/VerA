//! The Zig text `compileRelease` and `buildEngine` write next to a device:
//! each artifact's root file (`shim*.zig`, `vera_engine_*.zig`), which binds
//! the device to the host's `dyn` module. Build options in, source text out.
//! Every byte here reaches a `zig` child and is frozen: the goldens hold
//! `device`'s text (`.so/shim.zig`), and only the tests below pin the part,
//! chunk and engine roots.

const std = @import("std");
const Allocator = std.mem.Allocator;
const Part = @import("orchestrator.zig").Part;
const assert = std.debug.assert;

/// Returns the `shim_<piece>.zig` file name of a split build's piece.
/// Asserts that `piece` is not empty.
pub fn fileName(arena: Allocator, piece: []const u8) ![]const u8 {
    assert(piece.len > 0);
    return arena.print("shim_{s}.zig", .{piece});
}

/// Returns the dyn-ABI export shim, which re-exports the device under the
/// host's C ABI. It depends only on `name` and whether `engine` is linked,
/// so rebuilds never dirty it. Caller owns the text and frees it with `gpa`.
pub fn device(gpa: Allocator, name: []const u8, engine: bool) ![]u8 {
    return gpa.print(
        \\// GENERATED BY VerA — DO NOT EDIT.
        \\{s}comptime {{
        \\    @import("dyn").exportDevice(@import("device"), "{f}");
        \\}}
        \\
    , .{ rootDecls(engine), std.zig.fmtString(name) });
}

/// The shim's root declarations: the `dyn` host's opt-in to the contract's
/// conformance checks, forwarded because the shim, not `dyn`, is the root
/// `contract.validating` reads; and, with `engine`, the one that makes
/// `sim`'s runtime call the linked engine object (`rt.prebuilt`).
fn rootDecls(engine: bool) []const u8 {
    const validate =
        "pub const vera_validate_contract = @hasDecl(@import(\"dyn\"), \"vera_validate_contract\") and " ++
        "@import(\"dyn\").vera_validate_contract;\n";
    return if (engine) validate ++ "pub const vera_prebuilt_engine = {};\n" else validate;
}

/// The root of one part's object: the host's `exportDevicePart` for that
/// part, or, for a host without one, its `exportDevice` in the setup object
/// and nothing in the others. With `chunks` (a `setup` emitted as chunks),
/// every part calls the chunks through their objects (`chunk`)
/// when the host names its value scalar. Allocated in `arena`.
pub fn part(arena: Allocator, name: []const u8, which: Part, engine: bool, chunks: bool) ![]u8 {
    const head = try std.mem.concat(arena, u8, &.{ rootDecls(engine), if (chunks) setup_split_decl else "" });
    return if (which == .setup) arena.print(
        \\// GENERATED BY VerA — DO NOT EDIT.
        \\{1s}comptime {{
        \\    const dyn = @import("dyn");
        \\    if (@hasDecl(dyn, "exportDevicePart"))
        \\        dyn.exportDevicePart(@import("device"), "{0f}", .setup)
        \\    else
        \\        dyn.exportDevice(@import("device"), "{0f}");
        \\}}
        \\
    , .{ std.zig.fmtString(name), head }) else arena.print(
        \\// GENERATED BY VerA — DO NOT EDIT.
        \\{s}comptime {{
        \\    const dyn = @import("dyn");
        \\    if (@hasDecl(dyn, "exportDevicePart")) dyn.exportDevicePart(@import("device"), "{f}", .{t});
        \\}}
        \\
    , .{ head, std.zig.fmtString(name), which });
}

/// A split build's parts call `setup`'s chunks through the chunk objects
/// exactly when the chunk objects export them: when the host names the
/// value scalar it passes `setup` (`contract.DevicePart`).
const setup_split_decl = "pub const vera_setup_split = @hasDecl(@import(\"dyn\"), \"SetupValue\");\n";

// `part` and `chunk` splice the root declarations in front of `comptime {`:
// each must be whole lines.
comptime {
    assert(std.mem.endsWith(u8, setup_split_decl, "\n"));
    assert(std.mem.endsWith(u8, rootDecls(false), "\n"));
    assert(std.mem.endsWith(u8, rootDecls(true), "\n"));
}

/// The root of setup chunk `k`'s object: the chunk, for the host's value
/// scalar, or nothing for a host that does not name one. Allocated in `arena`.
pub fn chunk(arena: Allocator, k: u32, engine: bool) ![]u8 {
    return arena.print(
        \\// GENERATED BY VerA — DO NOT EDIT.
        \\{s}{s}comptime {{
        \\    const dyn = @import("dyn");
        \\    const D = @import("device");
        \\    if (@hasDecl(dyn, "SetupValue")) D.setup_chunks.exportChunk(dyn.SetupValue(D), {d});
        \\}}
        \\
    , .{ rootDecls(engine), setup_split_decl, k });
}

/// The root of the engine object: `sim`'s runtime, with no root options
/// (a device's shim declares none).
pub const engine_root =
    \\// GENERATED BY VerA — DO NOT EDIT.
    \\comptime {
    \\    @import("sim").rt.engine.exportAll();
    \\}
    \\
;

// ---- tests ------------------------------------------------------------------
// The expected texts are written out by hand from the format strings above:
// every byte here reaches a `zig` child, so each test pins one whole file.

test fileName {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    try std.testing.expectEqualStrings("shim_setup.zig", try fileName(arena.allocator(), "setup"));
    try std.testing.expectEqualStrings("shim_setup12.zig", try fileName(arena.allocator(), "setup12"));
}

test device {
    const gpa = std.testing.allocator;
    const plain = try device(gpa, "dev", false);
    defer gpa.free(plain);
    try std.testing.expectEqualStrings(
        \\// GENERATED BY VerA — DO NOT EDIT.
        \\pub const vera_validate_contract = @hasDecl(@import("dyn"), "vera_validate_contract") and @import("dyn").vera_validate_contract;
        \\comptime {
        \\    @import("dyn").exportDevice(@import("device"), "dev");
        \\}
        \\
    , plain);

    // `engine` adds exactly the prebuilt-engine declaration.
    const linked = try device(gpa, "dev", true);
    defer gpa.free(linked);
    try std.testing.expectEqualStrings(
        \\// GENERATED BY VerA — DO NOT EDIT.
        \\pub const vera_validate_contract = @hasDecl(@import("dyn"), "vera_validate_contract") and @import("dyn").vera_validate_contract;
        \\pub const vera_prebuilt_engine = {};
        \\comptime {
        \\    @import("dyn").exportDevice(@import("device"), "dev");
        \\}
        \\
    , linked);
}

test part {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();

    // `setup` falls back to the whole device for a host without parts.
    try std.testing.expectEqualStrings(
        \\// GENERATED BY VerA — DO NOT EDIT.
        \\pub const vera_validate_contract = @hasDecl(@import("dyn"), "vera_validate_contract") and @import("dyn").vera_validate_contract;
        \\comptime {
        \\    const dyn = @import("dyn");
        \\    if (@hasDecl(dyn, "exportDevicePart"))
        \\        dyn.exportDevicePart(@import("device"), "dev", .setup)
        \\    else
        \\        dyn.exportDevice(@import("device"), "dev");
        \\}
        \\
    , try part(a, "dev", .setup, false, false));

    // Any other part exports nothing for such a host; `engine` and `chunks`
    // each add their declaration, in that order after the validate line.
    try std.testing.expectEqualStrings(
        \\// GENERATED BY VerA — DO NOT EDIT.
        \\pub const vera_validate_contract = @hasDecl(@import("dyn"), "vera_validate_contract") and @import("dyn").vera_validate_contract;
        \\pub const vera_prebuilt_engine = {};
        \\pub const vera_setup_split = @hasDecl(@import("dyn"), "SetupValue");
        \\comptime {
        \\    const dyn = @import("dyn");
        \\    if (@hasDecl(dyn, "exportDevicePart")) dyn.exportDevicePart(@import("device"), "dev", .eval);
        \\}
        \\
    , try part(a, "dev", .eval, true, true));

    const state_tail =
        \\    if (@hasDecl(dyn, "exportDevicePart")) dyn.exportDevicePart(@import("device"), "dev", .state);
        \\}
        \\
    ;
    try std.testing.expect(std.mem.endsWith(u8, try part(a, "dev", .state, false, false), state_tail));
}

test chunk {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    try std.testing.expectEqualStrings(
        \\// GENERATED BY VerA — DO NOT EDIT.
        \\pub const vera_validate_contract = @hasDecl(@import("dyn"), "vera_validate_contract") and @import("dyn").vera_validate_contract;
        \\pub const vera_setup_split = @hasDecl(@import("dyn"), "SetupValue");
        \\comptime {
        \\    const dyn = @import("dyn");
        \\    const D = @import("device");
        \\    if (@hasDecl(dyn, "SetupValue")) D.setup_chunks.exportChunk(dyn.SetupValue(D), 7);
        \\}
        \\
    , try chunk(arena.allocator(), 7, false));
}

/// Fails the test unless `text` parses as Zig with no error.
fn expectParses(text: []const u8) !void {
    const gpa = std.testing.allocator;
    const z = try gpa.dupeSentinel(u8, text, 0);
    defer gpa.free(z);
    var tree = try std.zig.Ast.parse(gpa, z, .{});
    defer tree.deinit(gpa);
    try std.testing.expectEqual(@as(usize, 0), tree.errors.len);
}

test "every shim is Zig source whatever bytes the device name holds" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();

    try expectParses(engine_root);
    // IEEE 1364-2005 §3.7.1: an escaped identifier holds any printable ASCII
    // byte, `"` and `\` included, and a digital module's name reaches
    // `Options.name` as written (src/cli/digital.zig).
    for ([_][]const u8{ "dev", "a$b", "a\"b", "back\\slash", "x\"); @compileError(\"" }) |name| {
        try expectParses(try device(a, name, false));
        for (std.enums.values(Part)) |p| try expectParses(try part(a, name, p, true, true));
    }
    try expectParses(try chunk(a, 0, true));

    // The name round-trips as a string literal: Zig's own escapes, written
    // out by hand.
    try std.testing.expect(std.mem.find(u8, try device(a, "a\"b", false), "\"a\\\"b\"") != null);
    try std.testing.expect(std.mem.find(u8, try device(a, "back\\slash", false), "\"back\\\\slash\"") != null);
}
