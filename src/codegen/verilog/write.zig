//! The settled logic functions in, the module's IEEE 1364-2005 text out:
//! header comment, port list and declarations (§12.3), one internal net per
//! live state that is no digital port, and per live state its truth table
//! (an `always @*` `case`, §9.5) and an inertial `assign #(rise, fall)`
//! (§6.1.3), so a pulse shorter than the delay is swallowed as an RC would.
//! An input that is x or z selects no row and drives x. Names are §3.7
//! identifiers, escaped (§3.7.1) when not simple.
//!
//! Contents:
//! - `pub const Plan = struct`
//! - `pub fn firstSignal(pins: []const Pin, power_pins: bool) ?u32`
//! - `pub fn write(w: *std.Io.Writer, plan: *const Plan) std.Io.Writer.Error!void`
//! - `pub fn Name.format(n: Name, w: *Writer) Writer.Error!void` (the `{f}` hook of a private type)

const std = @import("std");
const assert = std.debug.assert;
const Writer = std.Io.Writer;
const Pin = @import("ports.zig").Pin;
const Drive = @import("drive.zig").Drive;
const Settled = @import("settle.zig").Settled;

/// Everything the text is a function of. Borrows every slice.
pub const Plan = struct {
    /// The module's name, printed as is.
    module: []const u8,
    /// The `.va` path the header names.
    source: []const u8,
    vdd: f64,
    /// `--power-pins`: supply ports only under `` `ifdef USE_POWER_PINS ``.
    power_pins: bool,
    /// `Lowered.nodes`' name column; the ports are its first `pins.len`.
    names: []const []const u8,
    /// One per port.
    pins: []const Pin,
    drive: Drive,
    settled: Settled,
    /// Bit `si`: state `si` is emitted (`settle.liveStates`).
    live: u32,
};

/// A Verilog name: `prefix` then `text`, or (no prefix) `text` itself, as one
/// legal identifier, escaped (§3.7.1) when it is not a simple one. Distinct
/// texts under one prefix are distinct names.
const Name = struct {
    prefix: ?[]const u8 = null,
    text: []const u8,

    /// Writes the name as an IEEE 1364-2005 §3.7 identifier.
    pub fn format(n: Name, w: *Writer) Writer.Error!void {
        const plain = for (n.text) |c| {
            if (!(std.ascii.isAlphanumeric(c) or c == '_' or c == '$')) break false;
        } else true;
        if (n.prefix) |p| {
            assert(p.len > 0);
            // The prefix starts the identifier, so any text of identifier
            // bytes keeps it simple. Any other text escapes the whole name
            // rather than map its bytes onto `_`, which two texts could share.
            if (plain) return w.print("{s}{s}", .{ p, n.text });
            return w.print("\\{s}{s} ", .{ p, n.text });
        }
        if (plain and n.text.len != 0 and !std.ascii.isDigit(n.text[0]) and n.text[0] != '$') return w.writeAll(n.text);
        try w.print("\\{s} ", .{n.text});
    }
};

/// Returns the first port that is not a supply hidden by `power_pins`, or
/// null when every port is one, which leaves no module to write.
pub fn firstSignal(pins: []const Pin, power_pins: bool) ?u32 {
    for (pins, 0..) |p, i| {
        if (hidden(power_pins, p)) continue;
        assert(i < pins.len);
        return @intCast(i);
    }
    // Only hidden supplies are left, which `--power-pins` alone hides.
    if (pins.len > 0) assert(power_pins);
    return null;
}

/// Writes the module. Asserts that `firstSignal` is not null and that every
/// live state's delays are finite in ns.
pub fn write(w: *Writer, plan: *const Plan) Writer.Error!void {
    const first_signal = firstSignal(plan.pins, plan.power_pins).?;
    assert(plan.drive.states().len == plan.settled.support.len);
    const ports = plan.names[0..plan.pins.len];
    try w.print("// GENERATED BY VerA --emit-verilog from {s} - DO NOT EDIT.\n", .{plan.source});
    try w.print(
        \\// Behavioural model of `{s}` for digital simulation: a driven net is high
        \\// above VDD/2 = {d} V; its switching delay is the model's own RC (tau*ln2) plus
        \\// any transition()/absdelay() td, or its (* vera_delay *). Analog pins are
        \\// undriven and read as their logic level.
        \\`timescale 1ns/1ps
        \\module {s} (
        \\
    , .{ plan.module, plan.vdd / 2, plan.module });

    // The port list: a leading supply carries its own comma, every later
    // port a leading one, so either side of an `ifdef` closes cleanly.
    var in_ifdef = false;
    for (plan.pins, ports, 0..) |p, name, i| {
        try powerIfdef(w, plan.power_pins, p, &in_ifdef);
        if (i < first_signal) {
            try w.print("    {f},\n", .{ident(name)});
        } else try w.print("    {s}{f}\n", .{ if (i == first_signal) "  " else ", ", ident(name) });
    }
    if (in_ifdef) try w.writeAll("`endif\n");
    try w.writeAll(");\n");

    in_ifdef = false;
    for (plan.pins, ports, 0..) |p, name, i| {
        try powerIfdef(w, plan.power_pins, p, &in_ifdef);
        const dir: []const u8, const what: []const u8 = switch (p) {
            .digital => if (plan.drive.driven.isSet(i)) .{ "output", "digital" } else .{ "input ", "digital" },
            .analog => .{ "inout ", "analog, undriven" },
            .power => .{ "inout ", "power" },
            .ground => .{ "inout ", "ground" },
        };
        try w.print("    {s} wire {f}; // {s}\n", .{ dir, ident(name), what });
    }
    if (in_ifdef) try w.writeAll("`endif\n");

    // Internal nets: every live state that is not a digital port.
    const states = plan.drive.states();
    for (states, 0..) |r, si| {
        if (plan.live >> @intCast(si) & 1 == 0 or isDigitalPort(plan, r)) continue;
        try w.print("    wire {f}; // {s}\n", .{ net(plan, r), plan.names[r] });
    }
    for (states, 0..) |r, si| {
        if (plan.live >> @intCast(si) & 1 == 1) try node(w, plan, si, r);
    }
    try w.writeAll("endmodule\n");
}

// ---- private ----

fn ident(text: []const u8) Name {
    return .{ .text = text };
}

fn hidden(power_pins: bool, p: Pin) bool {
    return power_pins and (p == .power or p == .ground);
}

/// Opens or closes `` `ifdef USE_POWER_PINS `` as the port list crosses
/// from signal pins to hidden supply pins or back.
fn powerIfdef(w: *Writer, power_pins: bool, p: Pin, in_ifdef: *bool) Writer.Error!void {
    const h = hidden(power_pins, p);
    if (h == in_ifdef.*) return;
    // An `ifdef` opens only on a hidden supply.
    if (h) assert(power_pins);
    try w.writeAll(if (h) "`ifdef USE_POWER_PINS\n" else "`endif\n");
    in_ifdef.* = h;
}

fn isDigitalPort(plan: *const Plan, r: u32) bool {
    return r < plan.pins.len and plan.pins[r] == .digital;
}

/// The Verilog net that carries row `r`'s bit: a digital or an undriven
/// port itself, else an internal `vera_n_*` (a driven analog port stays
/// undriven outside).
fn net(plan: *const Plan, r: u32) Name {
    assert(r < plan.names.len);
    const name = plan.names[r];
    if (isDigitalPort(plan, r) or (r < plan.pins.len and !plan.drive.driven.isSet(r))) return ident(name);
    return .{ .prefix = "vera_n_", .text = name };
}

/// Writes state `si` (row `r`): its delays, its table over its support, and
/// its delayed assignment.
fn node(w: *Writer, plan: *const Plan, si: usize, r: u32) Writer.Error!void {
    const s = &plan.settled;
    const rise_s = s.rise_s[si];
    const fall_s = s.fall_s[si];
    // `settle` refused a delay with no finite ns value.
    assert(std.math.isFinite(rise_s * 1e9));
    assert(std.math.isFinite(fall_s * 1e9));
    const support = s.support[si];
    const vars = plan.drive.vars;
    assert(support >> @intCast(vars.len) == 0);
    const table = s.table(si);
    const width: u5 = @intCast(@popCount(support));

    const name = plan.names[r];
    const t: Name = .{ .prefix = "vera_t_", .text = name };
    const rise: Name = .{ .prefix = "vera_rise_", .text = name };
    const fall: Name = .{ .prefix = "vera_fall_", .text = name };
    try w.print("\n    // {s}\n", .{name});
    try w.print("    parameter real {f} = {d:.6}; // ns\n", .{ rise, rise_s * 1e9 });
    try w.print("    parameter real {f} = {d:.6}; // ns\n", .{ fall, fall_s * 1e9 });
    if (width == 0) {
        try w.print("    wire {f} = 1'b{t};\n", .{ t, table[0] });
    } else {
        // The case selector lists the support's nets, highest variable
        // first, so bit `j` of a row's label is the `j`-th variable.
        try w.print("    reg {f};\n    always @* begin\n        case ({{", .{t});
        var k: usize = vars.len;
        var listed: u5 = 0;
        while (k > 0) {
            k -= 1;
            if (support >> @intCast(k) & 1 == 0) continue;
            listed += 1;
            try w.print("{f}{s}", .{ net(plan, vars[k]), if (listed == width) "" else ", " });
        }
        assert(listed == width);
        try w.writeAll("})\n");
        for (table, 0..) |bit, sub| {
            try w.print("            {d}'b", .{width});
            var j: usize = width;
            while (j > 0) {
                j -= 1;
                try w.writeByte(if (sub >> @intCast(j) & 1 == 1) '1' else '0');
            }
            try w.print(": {f} = 1'b{t};\n", .{ t, bit });
        }
        try w.print("            default: {f} = 1'bx;\n        endcase\n    end\n", .{t});
    }
    try w.print("    assign #({f}, {f}) {f} = {f};\n", .{ rise, fall, net(plan, r), t });
}

test Name {
    // A simple identifier (IEEE 1364-2005 §3.7) is written as is, `$` inside
    // included; anything else is escaped: `\`, the text, a space (§3.7.1).
    try std.testing.expectFmt("a$b", "{f}", .{ident("a$b")});
    try std.testing.expectFmt("\\1a ", "{f}", .{ident("1a")});
    try std.testing.expectFmt("\\$a ", "{f}", .{ident("$a")});
    try std.testing.expectFmt("\\a.b ", "{f}", .{ident("a.b")});
    // A prefixed name keeps a simple text as it is ...
    try std.testing.expectFmt("vera_n_a_b", "{f}", .{Name{ .prefix = "vera_n_", .text = "a_b" }});
    // ... and two texts never meet in one name: `a.b` is not `a_b`.
    try std.testing.expectFmt("\\vera_n_a.b ", "{f}", .{Name{ .prefix = "vera_n_", .text = "a.b" }});
    try std.testing.expectFmt("vera_n_a$b", "{f}", .{Name{ .prefix = "vera_n_", .text = "a$b" }});
}

test firstSignal {
    try std.testing.expectEqual(@as(?u32, 0), firstSignal(&.{ .power, .digital }, false));
    try std.testing.expectEqual(@as(?u32, 1), firstSignal(&.{ .power, .digital }, true));
    try std.testing.expectEqual(@as(?u32, null), firstSignal(&.{ .power, .ground }, true));
    // An empty port list has no signal either; `emit` refused it earlier.
    try std.testing.expectEqual(@as(?u32, null), firstSignal(&.{}, false));
}
