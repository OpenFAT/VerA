//! An elaborated `Run` and how `vera --emit-exe` was invoked -> the root
//! module of the design's executable: native (`native.zig`), or, when a
//! construct is not native, a root that embeds the source and runs the
//! interpreter (`rt.interpret`), so the executable still prints what
//! `vera --run` prints.
//! Cites: IEEE 1364-2005 §13.2 (libraries), §13.7.1 (`-L`), §19.3.1 (`-D`).
//!
//! Contents:
//! - `pub const Embed = struct`
//! - `pub const Program = struct`
//! - `pub fn program(arena: Allocator, r: *Run, embed: Embed, schedule: plan.Schedule, logic: Emitter.Logic) Allocator.Error!Program`

const std = @import("std");
const assert = std.debug.assert;
const Allocator = std.mem.Allocator;
const Front = @import("frontend");
const sim_digital = @import("sim").digital;
const Run = sim_digital.Run;
const deep = @import("base").deep_stack;
const Emitter = @import("Emitter.zig");
const native = @import("native.zig");
const plan = @import("plan.zig");

/// What `vera --emit-exe design.v` was given: enough to run the source again.
pub const Embed = struct {
    /// The design's source text, before preprocessing.
    source: []const u8,
    /// The name diagnostics and `$finish` reports give the source.
    file_name: []const u8,
    /// `-I` directories, searched by `` `include ``.
    include_dirs: []const []const u8,
    /// `-D` macros.
    defines: []const []const u8 = &.{},
    /// `--std=`'s keyword set.
    language: Front.token.KeywordSet,
    /// §13.2.3 the library the source maps into.
    lib: []const u8 = "work",
    /// More sources, each with its own library (§13.2).
    more: []const sim_digital.Unit = &.{},
    /// §13.7.1 `-L`'s library search order; empty is the default order.
    search: []const []const u8 = &.{},
};

/// What `program` made: the executable's root text, native or not.
pub const Program = struct {
    /// The executable's root module.
    text: []const u8,
    /// Null when the design runs natively; else why it does not.
    fallback: ?[]const u8,
    /// `.auto`, native: why the executable is 4-state throughout; null when
    /// it carries both phases (`rt.auto`).
    four: ?Emitter.Reason = null,
};

/// Returns the root module of `r`'s executable. `r` is read and its time-0
/// queue drained, never run. Under `.two` a design where an x or z carries
/// meaning is refused; under `.auto` it is 4-state throughout
/// (`Program.four`). A refused design's root embeds `embed` and runs the
/// interpreter. Every returned slice is in `arena`. Runs on a reserved deep
/// stack: the walks recurse on expression depth.
pub fn program(arena: Allocator, r: *Run, embed: Embed, schedule: plan.Schedule, logic: Emitter.Logic) Allocator.Error!Program {
    return deep.runGuarded(0, programDeep, .{ arena, r, embed, schedule, logic });
}

// ---- private ----

fn programDeep(arena: Allocator, r: *Run, embed: Embed, schedule: plan.Schedule, logic: Emitter.Logic) Allocator.Error!Program {
    // Emitting compiles `r`, it does not run it: what it raises through `r`
    // is a compile error (#72).
    r.diag_stage = .lower;
    var em: Emitter = .init(arena, r, .executable, logic);
    if (native.native(&em, embed.file_name, schedule)) |text| {
        if (logic != .auto) assert(em.four == null);
        return .{ .text = text, .fallback = null, .four = em.four };
    } else |err| switch (err) {
        error.OutOfMemory => return error.OutOfMemory,
        error.Unsupported => {
            assert(em.why.len != 0);
            return .{ .text = try interpreted(arena, embed, em.why), .fallback = em.why };
        },
    }
}

/// The interpreter fallback's root: `rt.interpret` of the embedded source,
/// with the options it was elaborated under.
fn interpreted(arena: Allocator, embed: Embed, why: []const u8) Allocator.Error![]const u8 {
    assert(why.len != 0);
    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    w.print(
        \\// GENERATED BY VerA — DO NOT EDIT. {f}
        \\// Not native ({s}): the embedded source runs through the interpreter.
        \\const std = @import("std");
        \\pub fn main(init: std.process.Init) u8 {{
        \\    return @import("sim").rt.interpret(init, .{{ .file_name = "{f}", .language = .{t}, .include_dirs = &.{{
    , .{ std.zig.fmtString(embed.file_name), why, std.zig.fmtString(embed.file_name), embed.language }) catch return error.OutOfMemory;
    for (embed.include_dirs) |d| w.print(" \"{f}\",", .{std.zig.fmtString(d)}) catch return error.OutOfMemory;
    w.writeAll(" }, .defines = &.{") catch return error.OutOfMemory;
    for (embed.defines) |d| w.print(" \"{f}\",", .{std.zig.fmtString(d)}) catch return error.OutOfMemory;
    w.print(" }}, .lib = \"{f}\", .more = &.{{", .{std.zig.fmtString(embed.lib)}) catch return error.OutOfMemory;
    for (embed.more) |u| w.print(" .{{ .name = \"{f}\", .text = \"{f}\", .lib = \"{f}\" }},", .{ std.zig.fmtString(u.name), std.zig.fmtString(u.text), std.zig.fmtString(u.lib) }) catch return error.OutOfMemory;
    w.writeAll(" }, .search = &.{") catch return error.OutOfMemory;
    for (embed.search) |l| w.print(" \"{f}\",", .{std.zig.fmtString(l)}) catch return error.OutOfMemory;
    w.print(" }} }}, \"{f}\");\n}}\n", .{std.zig.fmtString(embed.source)}) catch return error.OutOfMemory;
    assert(out.written().len != 0);
    return out.written();
}
