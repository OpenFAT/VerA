//! An elaborated `Run` -> the native Zig root of its executable or device:
//! the spine that lays the planes out, collects the processes from the
//! time-0 queue, plans their scheduling, writes every process, subroutine
//! and settle function once per `rt.Phase` (`Code(two)`), then the
//! `rt.Design` tables and `main` (or the device's contract decls). A
//! construct that is not native refuses by name (`Emitter.why`).
//! Cites: IEEE 1364-2005 §6.1, §9.9, §10.2.3, §11.4.2, §15 (refused), §17.1,
//! §18; VAMS §9.22 (driver access, refused); A.2.2.3 (a variable delay3,
//! refused).
//!
//! Contents:
//! - `pub fn native(em: *Emitter, file_name: []const u8, schedule: plan.Schedule) Error![]const u8`

const std = @import("std");
const assert = std.debug.assert;
const sim_digital = @import("sim").digital;
const Run = sim_digital.Run;
const Emitter = @import("Emitter.zig");
const Error = Emitter.Error;
const calls = @import("calls.zig");
const design_table = @import("design_table.zig");
const device = @import("device.zig");
const drivers = @import("drivers.zig");
const layout = @import("layout.zig");
const nets = @import("nets.zig");
const plan = @import("plan.zig");
const processes = @import("processes.zig");
const settle = @import("settle.zig");
const show = @import("show.zig");
const timing = @import("timing.zig");

/// Returns the native root of `em.r`, or `error.Unsupported` with `em.why`
/// set. `em.r` is read and its time-0 queue drained, never run. Asserts that
/// nothing was written yet.
pub fn native(em: *Emitter, file_name: []const u8, schedule: plan.Schedule) Error![]const u8 {
    const r = em.r;
    assert(em.out.written().len == 0);
    // `rt` keeps a driver's delay as the constant ticks `Driver.delay` holds.
    if (r.netlist.driver_delays.count() != 0) return em.refuse("A.2.2.3 a continuous assignment or gate delay that reads a variable");
    em.planes = try layout.planes(em.arena, r);
    try em.sub_seen.resize(em.arena, r.routines.rows.items.len, false);
    em.forced = try layout.forcedParts(em.arena, r);
    em.block_ends = try layout.blockEnds(em.arena, r);
    if (r.drv.watched.items.len != 0) return em.refuse("VAMS §9.22 driver access");
    // `rt` evaluates no timing check; the interpreter does (`tchk.zig`).
    if (r.checks.rows.items.len != 0) return em.refuse("IEEE 1364-2005 §15 timing checks");
    // §7.6: what a switch passes is a strength, which an x or z carries.
    if (r.netlist.switches.len != 0) try em.xMeaning("a §7.6 pass switch", null);
    em.port_files = try nets.portDumps(em);
    em.rt = try nets.resolvedNets(em);
    const order = try timeZeroOrder(em);

    try em.print(
        \\// GENERATED BY VerA — DO NOT EDIT. {f}
        \\const std = @import("std");
        \\const rt = @import("sim").rt;
        \\const L = rt.logic;
        \\const S = rt.State;
        \\
    , .{std.zig.fmtString(file_name)});
    if (em.logic == .two) try em.print("pub const vera_two_state = true;\n", .{});
    if (em.forced.part_start.len != 0) try em.print("pub const vera_overrides = true;\n", .{});
    if (r.event_budget.max != sim_digital.max_events_per_tick) try em.print("pub const vera_event_budget: u64 = {d};\n", .{r.event_budget.max});
    // Every function of the design, once per phase (`rt.Phase`): `main`
    // names `Code(true)` only when it runs both, and Zig compiles only what
    // is named.
    const decls_at = em.out.written().len;
    try em.print("\nfn Code(comptime two: bool) type {{\nreturn struct {{\nconst M = rt.Phase(two);\n\n", .{});
    const seen = try em.arena.alloc(bool, r.program.code.items.len);
    @memset(seen, false);
    const procs = try collectProcesses(em, order, seen);
    const activations = em.timed.items.len != 0;
    if (activations) try em.insert(decls_at, "pub const vera_activations = true;\n");
    const p = try plan.build(em, procs, schedule);
    em.watched = p.watched;
    em.reach = p.reach;
    em.pure_nodes = try settle.pureNodes(em, p.node_pc);
    // `fn proc<pc>` of every pc, so a dispatch is one indexed call.
    const entry_of = try em.arena.alloc(?u32, r.program.code.items.len);
    @memset(entry_of, null);
    for (procs) |pr| {
        em.site = .{ .role = pr.role };
        try processes.process(em, pr.pcs);
        for (pr.pcs) |pc| entry_of[pc] = pr.pcs[0];
    }
    // Selector expressions can call HDL functions. Emit them before the
    // subroutine worklist so those functions are emitted as well.
    try timing.eventSelectors(em);
    // §14.2.4 the module path conditions `rt.net` evaluates.
    try drivers.pathConds(em);
    try subroutines(em, seen, entry_of);
    try show.showSites(em);
    // A pure node's process runs only in the time-0 queue, which the
    // 2-state phase never sees (`rt.auto`): that phase leaves it uncompiled.
    const time0 = try em.arena.alloc(bool, r.program.code.items.len);
    @memset(time0, false);
    if (em.logic == .auto) for (procs) |pr| if (pr.role == .comb and r.program.code.items[pr.entry] == .continuous and em.pure_nodes[pr.role.comb]) {
        time0[pr.entry] = true;
    };
    try processes.dispatchTable(em, entry_of, time0, activations, p.node_pc.len != 0);
    if (p.node_pc.len != 0) try settle.settleFunctions(em, p, entry_of);
    try em.print("}};\n}}\n\n", .{});

    if (!advances(r)) em.keepFour("nothing delays, so the run never leaves time 0", null);
    const two_phase = em.logic == .auto and em.four == null;
    try timing.selectedEvents(em, two_phase);
    try design_table.design(em, p, procs, order, schedule, activations, two_phase);
    if (plan.dumps(r)) try design_table.catalog(em);
    switch (em.target) {
        .device => try device.contractDecls(em),
        .executable => if (two_phase) try em.print(
            \\pub fn main(init: std.process.Init) u8 {{
            \\    return rt.auto(init, &design, {d}, Code(false).dispatch, Code(true).dispatch);
            \\}}
            \\
        , .{r.time.finest}) else try em.print(
            \\pub fn main(init: std.process.Init) u8 {{
            \\    return rt.main(init, &design, {d}, Code(false).dispatch);
            \\}}
            \\
        , .{r.time.finest}),
    }
    assert(em.out.written().len > decls_at);
    return em.out.written();
}

// ---- private ----

/// The time-0 queue in `Run.rows.pending` order: every driver, declaration
/// assignment and process, as the pc it starts at. Drains `em.r.scheduler`.
fn timeZeroOrder(em: *Emitter) Error![]const u32 {
    const r = em.r;
    var order: std.ArrayList(u32) = .empty;
    // The time-0 queue holds at most one event per pending row.
    var events: usize = 0;
    while (r.scheduler.next()) |ev| : (events += 1) {
        assert(events < r.rows.pending.items.len);
        switch (r.rows.pending.items[ev.payload].item) {
            .run_process => |pc| try order.append(em.arena, pc),
            .@"resume", .write, .strobe, .monitor_tick, .vcd_tick, .tran_switch, .drive, .net_update, .decay, .a2d, .analog_point, .tchk_expiry, .tchk_event => return em.refuse("an event queued at elaboration"),
        }
    }
    return order.items;
}

/// The processes of `order`, each once, then the out-of-line body of every
/// timed task they reach (§10.2.3), which `processes.reach` queues as it
/// walks.
fn collectProcesses(em: *Emitter, order: []const u32, seen: []bool) Error![]plan.Proc {
    const r = em.r;
    var procs: std.ArrayList(plan.Proc) = .empty;
    for (order) |entry| {
        if (seen[entry]) continue;
        try procs.append(em.arena, .{ .entry = entry, .pcs = try processes.reach(em, entry, seen) });
    }
    var next_timed: usize = 0;
    while (next_timed < em.timed.items.len) : (next_timed += 1) {
        // Each timed task is queued once (`processes.reach`).
        assert(next_timed < r.routines.rows.items.len);
        const entry = r.routines.rows.items[em.timed.items[next_timed]].body.?.entry;
        if (!seen[entry]) try procs.append(em.arena, .{ .entry = entry, .pcs = try processes.reach(em, entry, seen) });
    }
    for (procs.items) |pr| assert(pr.pcs[0] == pr.entry);
    return procs.items;
}

/// The subroutines the processes call, and those they call in turn, each
/// as `fn proc<entry>`; a body is reached only through a call, which runs it
/// to completion. Then each automatic one's fresh frame, synchronous
/// (`fill<idx>`) or timed (`tfill<idx>`).
fn subroutines(em: *Emitter, seen: []bool, entry_of: []?u32) Error!void {
    const r = em.r;
    em.site = .{ .in_sub = true };
    var next_sub: usize = 0;
    while (next_sub < em.subs_todo.items.len) : (next_sub += 1) {
        // Each subroutine is queued once (`Emitter.sub_seen`).
        assert(next_sub < r.routines.rows.items.len);
        const idx = em.subs_todo.items[next_sub];
        const sub = r.routines.rows.items[idx];
        const pcs = try processes.reach(em, sub.entry, seen);
        try processes.process(em, pcs);
        for (pcs) |pc| entry_of[pc] = pcs[0];
        if (!sub.decl.automatic) continue;
        em.keepFour("an automatic task or function, whose storage is x at every call (§10.2.3)", null);
        try calls.fillTable(em, "fill", idx, sub.frame);
    }
    em.site = .{};
    for (em.timed.items) |idx| {
        const sub = r.routines.rows.items[idx];
        if (!sub.decl.automatic) continue;
        em.keepFour("an automatic task or function, whose storage is x at every call (§10.2.3)", null);
        try calls.fillTable(em, "tfill", idx, sub.body.?.frame);
    }
}

/// Whether simulation time can pass 0: a procedural, intra-assignment, net
/// or gate delay exists.
fn advances(r: *const Run) bool {
    for (r.program.code.items) |ins| if (ins == .delay or ins == .sample) return true;
    for (r.netlist.drivers) |d| if (d.delay.present) return true;
    for (r.netlist.cold.items) |c| if (c.delay.present) return true;
    return false;
}
