//! The `u/<key>.zig` file-scope prologue (see `Output.prelude`) and the
//! `h.zig` head: a helper text in, the `const zFoo = zh.zFoo;` aliases a unit
//! file needs out. A unit file is a separate Zig file with none of
//! device.zig's helpers in scope, so it aliases them from `h.zig`.
//! Cites: none (VerA's own unit-file layout, `zigbuild`).
//!
//! Contents:
//! - `pub const helpers_head_txt`
//! - `pub const prelude_head_txt`
//! - `pub fn appendAliases(out: *std.ArrayList(u8), gpa: Allocator, src: []const u8) Allocator.Error!void`
//! - `pub fn declKeyword(line: []const u8) ?usize`

const std = @import("std");
const assert = std.debug.assert;
const Allocator = std.mem.Allocator;

/// The `h.zig` header: banner and imports ahead of the public helper text.
pub const helpers_head_txt =
    \\// GENERATED BY VerA — DO NOT EDIT.
    \\// The §4.3/§4.5 kernels, public so `u/<key>.zig` can alias them. device.zig
    \\// carries the same text privately: it must stay a valid stand-alone device.
    \\const std = @import("std");
    \\const contract = @import("contract");
    \\
    \\
;

/// The unit-file prologue head: imports and aliases of the device's types.
/// The helper import is `zh`, not `h`: a unit body's hoist array is `var h`,
/// and Zig refuses a local that shadows a file-scope name. `..` is the
/// work_dir: `u/<key>.zig` sits one level under `device.zig`.
pub const prelude_head_txt =
    \\// GENERATED BY VerA — DO NOT EDIT.
    \\const std = @import("std");
    \\const contract = @import("contract");
    \\const dev = @import("../device.zig");
    \\const zh = @import("../h.zig");
    \\const U = dev.U;
    \\const Model = dev.Model;
    \\const Instance = dev.Instance;
    \\const InstancePtr = contract.InstancePtr(dev);
    \\const n_u = contract.nU(dev);
    \\
;

/// Appends a `const zFoo = zh.zFoo;` alias for each top-level `z*` helper
/// `src` declares, so a helper that is emitted is aliased by construction. A
/// line is a declaration by `publish`'s predicate (`fn `, `inline fn ` or
/// `const `, optionally `pub `), and the name must be `z` plus an uppercase
/// letter: the spelling of every helper an emitted body calls, which keeps a
/// kernel's internals (`zstd`, `zfIo`, `zf_max`, `ZScan`) out.
/// Invalidates slices of `out.items` if additional memory is needed; `out`
/// is allocated with `gpa`.
pub fn appendAliases(out: *std.ArrayList(u8), gpa: Allocator, src: []const u8) Allocator.Error!void {
    const len_before = out.items.len;
    // `splitScalar` yields at most one line per byte, plus the last.
    var lines: usize = 0;
    var it = std.mem.splitScalar(u8, src, '\n');
    while (it.next()) |line| {
        lines += 1;
        assert(lines <= src.len + 1);
        const decl = if (std.mem.startsWith(u8, line, "pub ")) line[4..] else line;
        const rest = decl[declKeyword(decl) orelse continue ..];
        var n: usize = 0;
        while (n < rest.len and (std.ascii.isAlphanumeric(rest[n]) or rest[n] == '_')) n += 1;
        const name = rest[0..n];
        if (name.len < 2 or name[0] != 'z' or !std.ascii.isUpper(name[1])) continue;
        try out.print(gpa, "const {0s} = zh.{0s};\n", .{name});
    }
    assert(out.items.len >= len_before);
}

/// Returns the length of the keyword that makes `line` a top-level helper
/// declaration (`fn `, `inline fn ` or `const `), or null. `publish` and
/// `appendAliases` share it, so every helper h.zig exports is aliased. The
/// length never exceeds `line.len`.
pub fn declKeyword(line: []const u8) ?usize {
    for ([_][]const u8{ "fn ", "inline fn ", "const " }) |kw| {
        if (!std.mem.startsWith(u8, line, kw)) continue;
        assert(kw.len <= line.len);
        return kw.len;
    }
    return null;
}

// ---- private ----

test appendAliases {
    const gpa = std.testing.allocator;
    var out: std.ArrayList(u8) = .empty;
    defer out.deinit(gpa);
    // Top-level `z` + uppercase helpers, with or without `pub`; nothing
    // indented, lowercase after the `z`, capitalised, one letter long, or
    // in a comment.
    try appendAliases(&out, gpa,
        \\fn zFoo() void {}
        \\pub fn zBar() void {}
        \\const zBaz = 1;
        \\pub const zQux = 2;
        \\inline fn zInl() void {}
        \\fn zlower() void {}
        \\const ZUpper = 3;
        \\    fn zIndented() void {}
        \\fn z() void {}
        \\// fn zComment() void {}
    );
    try std.testing.expectEqualStrings(
        \\const zFoo = zh.zFoo;
        \\const zBar = zh.zBar;
        \\const zBaz = zh.zBaz;
        \\const zQux = zh.zQux;
        \\const zInl = zh.zInl;
        \\
    , out.items);
}
