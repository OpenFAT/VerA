/// §9.4.3 integer padding, for a printing artifact or a device that formats
/// into a string. `std.fmt` writes `+42` for `{d:>5}`; §9.4.3 (like C's
/// `%5d`) writes ` 42`, so the rendered decimal is padded instead.
// 24 bytes is i64's widest decimal (20 chars) plus slack, so the
// `catch unreachable` cannot fire. A '0', '+' or ' ' flag never reaches
// `zPadInt`: `cg_display` composes those fields in scratch (`.cint`).
pub const display_txt =
    \\fn zPadInt(buf: []u8, v: i64) []const u8 { // §9.4.3 %<width>d
    \\    return std.mem.print(buf, "{d}", .{v}) catch unreachable;
    \\}
    \\
    \\/// §9.7 simulation control: the run ends here. Declared `f64` and not
    \\/// `noreturn` ON PURPOSE: statements after a §9.7.3 `$fatal` are legal
    \\/// dead code (exhaustive/011 writes `$finish; $stop;` after one), and a
    \\/// noreturn-typed call site would make Zig refuse the block for
    \\/// unreachable code. The value is never produced.
    \\fn zHalt(code: u8) f64 {
    \\    std.process.exit(code);
    \\}
    \\
    \\/// §9.7.1/§9.7.3 the moment a diagnostic reports, with no newline: the
    \\/// host's (`veraDiag` in the root: a dc sweep's variable in place of the
    \\/// time, and Table 9-25 level 2's statistics), or the time `t` when the
    \\/// root has none.
    \\fn zWhen(t: f64, level: u8) void {
    \\    if (comptime @hasDecl(@import("root"), "veraDiag")) return @import("root").veraDiag(t, level);
    \\    std.debug.print("t={d}", .{t});
    \\}
    \\
    \\/// §5.10.2 a `$finish` (1) or `$stop` (2) call, which the enclosing
    \\/// display wrapper (`zFinishPass`) performs after the pass: it can raise
    \\/// `final_step` and re-run the chain, which the per-task site cannot do
    \\/// (it holds a probe, not the solution vector).
    \\var zFinish: u8 = 0;
    \\
;

